// Utilities for Web Push Notification management in the browser
import { supabase, isSupabaseConfigured } from './supabase'

/**
 * Convert a base64url string (like a VAPID public key) to a Uint8Array
 * required by pushManager.subscribe({ applicationServerKey }).
 */
export function urlBase64ToUint8Array(base64String: string): Uint8Array {
  const padding = '='.repeat((4 - (base64String.length % 4)) % 4)
  const base64 = (base64String + padding).replace(/-/g, '+').replace(/_/g, '/')
  const rawData = window.atob(base64)
  const outputArray = new Uint8Array(rawData.length)
  for (let i = 0; i < rawData.length; ++i) {
    outputArray[i] = rawData.charCodeAt(i)
  }
  return outputArray
}

export interface PushSupportStatus {
  supported: boolean
  permission: NotificationPermission | 'unsupported'
  serviceWorkerReady: boolean
  hasVapidKey: boolean
}

/**
 * Check if the current browser environment supports Service Worker and Push API.
 */
export function checkPushSupport(): PushSupportStatus {
  if (typeof window === 'undefined') {
    return {
      supported: false,
      permission: 'unsupported',
      serviceWorkerReady: false,
      hasVapidKey: false,
    }
  }

  // Push API and Service Workers strictly require a secure context (HTTPS or localhost)
  const isSecure = Boolean(window.isSecureContext)

  const supported =
    isSecure &&
    'serviceWorker' in navigator &&
    'PushManager' in window &&
    'Notification' in window

  const vapidKey = import.meta.env.VITE_VAPID_PUBLIC_KEY || ''
  const hasVapidKey = Boolean(vapidKey && !vapidKey.includes('your-vapid-public-key'))

  let permission: NotificationPermission | 'unsupported' = 'unsupported'
  try {
    if (supported && typeof Notification !== 'undefined') {
      permission = Notification.permission
    }
  } catch {
    permission = 'unsupported'
  }

  return {
    supported,
    permission,
    serviceWorkerReady: false,
    hasVapidKey,
  }
}

/**
 * Register the public/sw.js service worker.
 */
export async function registerServiceWorker(): Promise<ServiceWorkerRegistration | null> {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator)) {
    return null
  }

  try {
    const registration = await navigator.serviceWorker.register('/sw.js', {
      scope: '/',
    })
    await navigator.serviceWorker.ready
    return registration
  } catch (err) {
    console.warn('Service worker registration failed:', err)
    return null
  }
}

/**
 * Get existing push subscription from active registration.
 */
export async function getExistingSubscription(): Promise<PushSubscription | null> {
  if (typeof window === 'undefined' || !('serviceWorker' in navigator)) {
    return null
  }

  try {
    const registration = await navigator.serviceWorker.ready
    return await registration.pushManager.getSubscription()
  } catch (err) {
    console.warn('Failed to get push subscription:', err)
    return null
  }
}

/**
 * Subscribe the user to Web Push using the VAPID public key and record subscription in Supabase.
 */
export async function subscribeToPush(userId: string): Promise<{
  subscription: PushSubscription | null
  error: Error | null
}> {
  const vapidKey = import.meta.env.VITE_VAPID_PUBLIC_KEY
  if (!vapidKey || vapidKey.includes('your-vapid-public-key')) {
    return {
      subscription: null,
      error: new Error('VAPID public key is not configured in VITE_VAPID_PUBLIC_KEY.'),
    }
  }

  if (typeof window === 'undefined' || !('Notification' in window)) {
    return {
      subscription: null,
      error: new Error('Notifications are not supported in this browser.'),
    }
  }

  // Request browser permission explicitly
  const permission = await Notification.requestPermission()
  if (permission !== 'granted') {
    return {
      subscription: null,
      error: new Error(
        permission === 'denied'
          ? 'Notification permission was denied. You can enable it in your browser site settings.'
          : 'Notification permission prompt was dismissed.',
      ),
    }
  }

  const registration = await registerServiceWorker()
  if (!registration) {
    return {
      subscription: null,
      error: new Error('Failed to register service worker for push notifications.'),
    }
  }

  try {
    const applicationServerKey = urlBase64ToUint8Array(vapidKey)
    const subscription = await registration.pushManager.subscribe({
      userVisibleOnly: true,
      applicationServerKey: applicationServerKey as BufferSource,
    })

    const subJson = subscription.toJSON()
    const endpoint = subscription.endpoint
    const p256dh = subJson.keys?.p256dh || ''
    const authKey = subJson.keys?.auth || ''

    if (!endpoint || !p256dh || !authKey) {
      return {
        subscription,
        error: new Error('Incomplete push subscription keys generated by browser.'),
      }
    }

    // Save to Supabase if configured
    if (isSupabaseConfigured) {
      const { error: dbError } = await supabase
        .from('browser_push_subscriptions')
        .upsert(
          {
            user_id: userId,
            endpoint,
            p256dh,
            auth_key: authKey,
            user_agent: typeof navigator !== 'undefined' ? navigator.userAgent : null,
            updated_at: new Date().toISOString(),
          },
          { onConflict: 'endpoint' },
        )

      if (dbError) {
        console.warn('Failed to store subscription in Supabase:', dbError.message)
      }
    }

    return { subscription, error: null }
  } catch (err: unknown) {
    const error = err instanceof Error ? err : new Error(String(err))
    return { subscription: null, error }
  }
}

/**
 * Unsubscribe from Web Push in the browser and remove the subscription record from Supabase.
 */
export async function unsubscribeFromPush(userId: string): Promise<{ success: boolean; error: Error | null }> {
  try {
    const subscription = await getExistingSubscription()
    if (subscription) {
      const endpoint = subscription.endpoint
      await subscription.unsubscribe()

      if (isSupabaseConfigured && userId) {
        await supabase
          .from('browser_push_subscriptions')
          .delete()
          .eq('user_id', userId)
          .eq('endpoint', endpoint)
      }
    }
    return { success: true, error: null }
  } catch (err: unknown) {
    const error = err instanceof Error ? err : new Error(String(err))
    return { success: false, error }
  }
}
